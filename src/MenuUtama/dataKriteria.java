    private void bSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bSimpanActionPerformed
        // TODO add your handling code here:
        String sql = "insert into Kriteria values (?,?,?,?)";
        try {
            PreparedStatement stat = connection.prepareStatement(sql);
            stat.setString(1, txtId.getText());
            stat.setString(2, txtKriteria.getText());
            stat.setString(3, cbSifatKriteria.getSelectedItem().toString());
            stat.setString(4, txtBobotPref.getText());
            
            stat.executeUpdate();
            JOptionPane.showMessageDialog(null, "Data Berhasil Disimpan");
            kosong();
            txtId.requestFocus();
            PUtama.removeAll();
            PUtama.repaint();
            PUtama.revalidate();

            PUtama.add(dataKriteria);
            PUtama.repaint();
            PUtama.revalidate();
            bSimpan.setVisible(true);
            datatable();
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Data Gagal Disimpan");
        }
    }//GEN-LAST:event_bSimpanActionPerformed

