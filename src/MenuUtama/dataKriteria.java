    private void bUbah1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bUbah1ActionPerformed
        // TODO add your handling code here:
        try{
            String sql="UPDATE Kriteria set namaKriteria=?,sifatKriteria=?,bobotPreferensi=? where ID='"+txtId.getText()+"'";
            PreparedStatement stat=connection.prepareStatement(sql);
            stat.setString(1, txtKriteria.getText());
            stat.setString(2, cbSifatKriteria.getSelectedItem().toString());
            stat.setString(3, txtBobotPref.getText().toString());
            
            stat.executeUpdate();
            JOptionPane.showMessageDialog(null,"Data Berhasil Diubah");
            kosong();
            txtId.requestFocus();
            PUtama.removeAll();
            PUtama.repaint();
            PUtama.revalidate();

            PUtama.add(dataKriteria);
            PUtama.repaint();
            PUtama.revalidate();
        }
        catch(SQLException e){
            JOptionPane.showMessageDialog(null,"Data Gagal Diubah"+e);
        }
        datatable();
    }//GEN-LAST:event_bUbah1ActionPerformed

