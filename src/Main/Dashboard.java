    public void showDayDateTime(){
        Calendar calendar = Calendar.getInstance();
        Date now = new Date();
        SimpleDateFormat dayFormat = new SimpleDateFormat("EEEE",new Locale("in","ID"));
        SimpleDateFormat dateFormat = new SimpleDateFormat("dd MMMM yyyy HH:mm:ss", new Locale("in", "ID"));
        String dayTime = dayFormat.format(calendar.getTime());
        String dateTime = dateFormat.format(now);
        LTgl.setText(dayTime+", "+dateTime);
    }
